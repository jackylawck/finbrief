def extract_text_from_pdf(file):
    pdf_reader = PdfReader(file)
    extracted_text = ""
    max_pages = min(len(pdf_reader.pages), 15)
    for i in range(max_pages):
        text = pdf_reader.pages[i].extract_text()
        if text:
            extracted_text += text + "\n"
    return extracted_text

# --- 6. 報告生成與 ISO 可追溯性元數據附加 ---
if st.button(t["btn_generate"]):
    if not consent_given:
        st.error(t["err_no_consent"])
    elif run_mode == t["mode_byok"] and not active_api_key:
        st.error(t["err_no_key"])
    elif not uploaded_file:
        st.warning(t["err_no_file"])
    elif not template.strip():
        st.warning(t["err_no_template"])
    else:
        file_type = uploaded_file.name.split('.')[-1].lower()
        extracted_content = ""

        with st.spinner("Processing file / 正在解析檔案關鍵內容..."):
            if file_type == 'pdf':
                extracted_content = extract_text_from_pdf(uploaded_file)
            elif file_type in ['xlsx', 'csv']:
                df = pd.read_excel(uploaded_file) if file_type == 'xlsx' else pd.read_csv(uploaded_file)
                extracted_content = df.to_string()

        with st.spinner("AI Analysis in progress / AI 正在載入 ISO 合規知識庫並進行分析..."):
            try:
                kb_text, kb_files = load_knowledge_base()
                full_system_prompt = t["system_prompt"] + kb_text

                user_prompt = f"""
                【Analysis Requirements / 分析要求】:
                {template}

                【Financial Data / 財務數據】:
                {extracted_content}
                """

                if run_mode == t["mode_free"]:
                    raw_report = call_free_open_llm(full_system_prompt, user_prompt)
                else:
                    client = OpenAI(
                        api_key=active_api_key,
                        base_url=base_url if 'base_url' in locals() and base_url else None
                    )
                    response = client.chat.completions.create(
                        model=selected_model,
                        messages=[
                            {"role": "system", "content": full_system_prompt},
                            {"role": "user", "content": user_prompt[:40000]}
                        ],
                        temperature=0.2
                    )
                    raw_report = response.choices[0].message.content

                # --- ISO 42001 可追溯性紀錄區塊 (Audit Trail Block) ---
                timestamp_str = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
                audit_trail = f"""

---
### 🛡️ AI Governance & ISO 42001 Audit Trail
* **Timestamp**: `{timestamp_str}`
* **Execution Mode**: `{run_mode}`
* **LLM Model**: `{selected_model}`
* **Input File**: `{uploaded_file.name}`
* **Loaded Knowledge Base**: `{', '.join(kb_files)}`
* **Compliance Frameworks**: HKFRS / IFRS / ISO 27001 (Data Minimization) / ISO 42001 (AIMS)
"""
                final_report = raw_report + audit_trail

                st.markdown("---")
                st.markdown(f"## {t['report_header']}")
                st.markdown(final_report)
                
                st.download_button(
                    label=t["btn_download"],
                    data=final_report,
                    file_name=f"FinBrief_Report_{lang_code}_{datetime.now().strftime('%Y%m%d')}.md",
                    mime="text/markdown"
                )

            except Exception as e:
                st.error(f"❌ AI Error: {str(e)}")
