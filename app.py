# --- 3. 動態讀取模組化知識庫 (Knowledge Base Loader) ---
@st.cache_data
def load_knowledge_base():
    kb_dir = "knowledge_base"
    combined_kb_content = ""
    loaded_files = []
    
    if os.path.exists(kb_dir):
        md_files = glob.glob(os.path.join(kb_dir, "*.md"))
        for file_path in md_files:
            try:
                with open(file_path, "r", encoding="utf-8") as f:
                    filename = os.path.basename(file_path)
                    loaded_files.append(filename)
                    combined_kb_content += f"\n\n--- 知識模組: {filename} ---\n"
                    combined_kb_content += f.read()
            except Exception:
                pass
                
    if combined_kb_content:
        return f"\n\n【綜合權威知識庫 / Unified Domain Knowledge Base】\n{combined_kb_content}", loaded_files
    else:
        return "\n\n【Default Knowledge】: Analyze under standard HKFRS/IFRS framework.", ["Default System Prompt"]

# --- 4. 免 Key LLM 呼叫函數 ---
def call_free_open_llm(system_prompt, user_prompt):
    try:
        truncated_prompt = user_prompt[:8000]
        prompt_text = f"System: {system_prompt}\nUser: {truncated_prompt}"
        encoded_prompt = urllib.parse.quote(prompt_text)
        
        url = f"https://text.pollinations.ai/{encoded_prompt}?model=openai"
        response = requests.get(url, timeout=45)
        
        if response.status_code == 200 and len(response.text.strip()) > 0:
            return response.text
    except Exception:
        pass 

    try:
        url_b = "https://text.pollinations.ai/"
        payload_b = {
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt[:6000]}
            ],
            "model": "qwen",
            "code": "beartoken"
        }
        res_b = requests.post(url_b, json=payload_b, timeout=45)
        if res_b.status_code == 200 and len(res_b.text.strip()) > 0:
            return res_b.text
    except Exception:
        pass

    raise Exception("免費 LLM Endpoint 目前流量較高 (402/429)。建議稍後再試，或切換至「🔑 BYOK 模式」輸入 API Key 獲得商業級穩定體驗。")

